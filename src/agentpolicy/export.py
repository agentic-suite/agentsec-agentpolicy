"""Policy export — one policy → harness formats (WBS M9 ``9.5``, CUJ-16).

Renders a loaded :class:`~agentpolicy.policy.models.Policy` as Cedar source and
as a **policyweave** compiled artifact, so the same reviewed policy compiles
outward for a harness/consumer instead of being re-authored per target.
"""

from __future__ import annotations

import json
from dataclasses import asdict
from typing import Any

from agentpolicy.cedar import policy as policy_mod
from agentpolicy.policy.models import Policy, Rule

#: The export targets.
TARGETS: tuple[str, ...] = ("cedar", "policyweave")

#: The schema id for the policyweave artifact.
POLICYWEAVE_SCHEMA = "policyweave.policy.v1"


def _rule_cedar(rule: Rule, index: int) -> str:
    """Render one rule to a Cedar ``permit``/``forbid`` with a reason comment."""
    conditions: list[str] = []
    if rule.tool != "*":
        conditions.append(f'resource.id == "{rule.tool}"')
    if rule.action != "*":
        conditions.append(f'context.verb == "{rule.action}"')
    if rule.environment != "*":
        conditions.append(f'context.environment == "{rule.environment}"')
    if rule.data_class != "*":
        conditions.append(f'context.data_class == "{rule.data_class}"')
    when = " && ".join(conditions) if conditions else "true"
    effect = "forbid" if rule.decision == "deny" else "permit"
    reason = rule.reason or "no reason recorded"
    return (
        f"// {reason}\n"
        f'@id("rule-{index}-{rule.decision}")\n'
        f"{effect} (principal, action, resource)\n"
        f"when {{ {when} }};"
    )


def cedar_source(policy: Policy) -> str:
    """Render a policy to Cedar source (one rule per ``permit``/``forbid``)."""
    header = (
        f"// agentpolicy → Cedar export\n"
        f"// posture: {policy.posture}  version: {policy.version}\n"
        f"// {len(policy.rules)} rule(s); generated by `agentpolicy export --format cedar`.\n"
    )
    body = "\n\n".join(_rule_cedar(rule, i) for i, rule in enumerate(policy.rules))
    return header + "\n" + body + "\n"


def export_policy(policy: Policy, *, target: str = "policyweave") -> dict[str, Any]:
    """Compile a policy to a target artifact.

    Args:
        policy: The loaded policy.
        target: ``cedar`` (text) or ``policyweave`` (the compiled artifact).

    Returns:
        For ``cedar``: ``{"target", "format", "cedar"}``.
        For ``policyweave``: the compiled artifact dict.

    Raises:
        ValueError: The target is unknown.
    """
    if target not in TARGETS:
        raise ValueError(f"unknown export target {target!r}; use one of {sorted(TARGETS)}")
    cedar = cedar_source(policy)
    if target == "cedar":
        return {"target": "cedar", "format": "cedar", "cedar": cedar}
    return {
        "target": "policyweave",
        "schema": POLICYWEAVE_SCHEMA,
        "version": policy.version,
        "posture": policy.posture,
        "policy_hash": policy_mod.policy_hash(cedar),
        "cedar": cedar,
        "rules": [asdict(rule) for rule in _jsonable_rules(policy.rules)],
        "environments": dict(policy.environments),
        "data_classes": dict(policy.data_classes),
    }


def _jsonable_rules(rules: tuple[Rule, ...]) -> tuple[Rule, ...]:
    """Rules with the condition tree reduced to plain dicts for JSON."""
    from dataclasses import asdict, replace

    from agentpolicy.policy.models import Condition

    result: list[Rule] = []
    for rule in rules:
        conditions = tuple(
            asdict(cond) if isinstance(cond, Condition) else cond
            for cond in rule.conditions
        )
        result.append(replace(rule, conditions=conditions))
    return tuple(result)


def render_export(policy: Policy, *, target: str = "policyweave") -> str:
    """Render the export as text (Cedar source, or a JSON policyweave artifact)."""
    artifact = export_policy(policy, target=target)
    if target == "cedar":
        return str(artifact["cedar"])
    return json.dumps(artifact, indent=2, sort_keys=True)


__all__ = [
    "POLICYWEAVE_SCHEMA",
    "TARGETS",
    "cedar_source",
    "export_policy",
    "render_export",
]
